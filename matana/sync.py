"""Build tools.js for the gift shelf from a Tools Desk export (one JSON per tool).
Usage: python3 sync.py <dir-with-tool-json-files>"""
import json, glob, os, sys
KIND = {"party":"משחק","music":"מוזיקה","stage":"במה","self":"ידע עצמי","therapy":"התבוננות","groups":"קבוצות","general":"לכולם"}
IDEAS = {
 "bediyuk-baerech":"כל אחד בטלפון שלו, אותה רמת קושי, ומי שפותר ראשון מנצח.",
 "numerology":"מכניסים את התאריך שלך, ואחר כך בודקים יחד את ההתאמה הזוגית.",
 "family-weave":"עוברים סביב השולחן, מכניסים את כל מי שיושב בו, וקוראים יחד מה כל אחד מביא למשפחה.",
 "mazalot":"כל אחד מדרג את עצמו, ואחר כך משווים.",
 "fruty-beat":"בונים מקצב מפירות, ומשמיעים אותו לכל השולחן.",
 "beat-it-notes":"מתחילים באזור התרגול, ואז עוברים לאזור המשחק ואוספים עשרה קלפים.",
 "fill-drill":"בונים מעבר אחד על הגריד, ומתרגלים אותו לאט עם המטרונום עד שהוא יושב.",
 "grapholog":"כותבים דף קצר על הרגע הזה, ומצלמים.",
 "chakra-compass":"רגע שקט עם אוזניות, ובסוף משתפים משפט אחד.",
 "maagal-hagashama":"בוחרים נושא אחד שמעסיק אותך, ומתחילים מהמשבצת הראשונה.",
 "values-galaxy":"כל אחד בוחר כוכב ומקריא את התובנה שקיבל.",
 "oganim":"פותרים חידה אחת ביום.",
 "politikalpi":"כל אחד עונה לבד, ואחר כך משווים בלי ויכוחים.",
 "meeting-sync":"מתכננים יחד את המפגש המשפחתי הבא.",
}
out = []
for f in sorted(glob.glob(os.path.join(sys.argv[1], "*.json"))):
    d = json.load(open(f)); tid = os.path.basename(f)[:-5]; d = d.get("data", d)
    if tid == "matana" or not d.get("url"): continue
    cats = d.get("cats") or ["general"]
    out.append({"id":tid,"gift":d.get("gift","off"),"order":d.get("order",99),"kind":KIND.get(cats[0],"כלי"),
                "name":d.get("name",""),"url":d["url"],"what":d.get("desc",""),"idea":IDEAS.get(tid,"")})
rank = {"instant":0,"request":1,"off":2}
out.sort(key=lambda t:(rank.get(t["gift"],2), t["kind"], t["order"]))
for t in out: t.pop("order")
helpers = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),"tools.js")).read()
helpers = helpers[helpers.index("window.giftEncode"):]
wa = "window.BOAZ_WA = \"\"; /* WhatsApp number for requests, international format without +. Empty = sender picks the chat. */\n"
js = "/* Generated by sync.py from the Tools Desk. gift: instant | request | off (off = hidden from the menu, still usable in gift links). */\n"+wa+"window.GIFT_TOOLS = "+json.dumps(out,ensure_ascii=False,indent=1)+";\n"+helpers
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),"tools.js"),"w").write(js)
print({k:[t["name"] for t in out if t["gift"]==k] for k in ("instant","request")})
